const assert=require('node:assert/strict');
const {rangeSpectrum,thinPoints,shiftedFeatures,corrWindow,timeToAudio,audioToTime,clampRange}=require('../tools/imu_speech_lab/dashboard.js');
const hz=200, rows=Array.from({length:2000},(_,i)=>[i/hz,Math.sin(2*Math.PI*25*i/hz),0,0,3*Math.sin(2*Math.PI*12.5*i/hz),0,0]);
const psd=rangeSpectrum(rows,hz);
assert.equal(psd.hz[psd.acc.indexOf(Math.max(...psd.acc))],25);
assert.ok(Math.abs(psd.acc.reduce((s,v)=>s+10**(v/10)*hz/256,0)-.5)<.01);
const broken=rows.slice(0,150).concat(rows.slice(1900));
assert.equal(rangeSpectrum(broken,hz).count,0);
const points=Array.from({length:10000},(_,i)=>[i,i===4311?100:0]);
assert.equal(Math.max(...thinPoints(points).map(p=>p[1])),100);
const audio=Array.from({length:500},(_,i)=>[i*.02+.01,1,.5,i*320,320,0]);
const f=Array.from({length:50},(_,i)=>[i*.2+.1,1,1,0]);
const aligned=shiftedFeatures(f,audio,16000,.2);
assert.equal(aligned[0][3],null);assert.equal(aligned[1][3],1);
assert.equal(shiftedFeatures(f,audio.slice(10),16000,0)[0][3],null);
assert.ok(Math.abs(timeToAudio(audio,4.06,16000,.2)-3.86)<1e-8);
assert.ok(Math.abs(audioToTime(audio,3.86,16000,.2)-4.06)<1e-8);
const withGap=audio.filter(r=>r[0]<1||r[0]>2);
assert.equal(timeToAudio(withGap,1.5,16000),null);
assert.deepEqual(clampRange(-5,5,0,100),[0,10]);
assert.deepEqual(clampRange(95,105,0,100),[90,100]);
const energy=Array.from({length:100},(_,i)=>Math.sin(i*1.23)**2+.1);
const corr=energy.map((v,i)=>[i*.2+.1,i>1?energy[i-2]:0,0,v]);
assert.ok(corrWindow(corr,1).r>.99999);assert.equal(corrWindow(corr,1).lag,.4);
console.log('Review: FFT power/frequency, gaps, extrema, audio offset, playback mapping, range clamp and lag passed.');
