def make_plan(seed=20261002):
    rng = random.Random(seed)
    plan = []
    for round_index in range(10):
        order = list(VARIANTS)
        rng.shuffle(order)
        for shape, category, variant, hint in order:
            plan.append(dict(shape=shape, category=category, variant=variant,
                             hint=hint, round=round_index + 1))
    return plan
