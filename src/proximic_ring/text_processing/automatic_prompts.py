def automatic_system_prompt(task, plan=None):
    if task == DICTATION:
        if plan is not None:
            raise ValueError("听写不应携带编辑计划")
        return AUTOMATIC_DICTATION_PROMPT
    if task != EDIT or not isinstance(plan, EditPlan):
        raise ValueError("自动编辑缺少有效的联合分类计划")
    selected = plan.as_dict()
    names = [EDIT_TASK_LABELS[k] for k in selected["tasks"]]
    modules = [EDIT_PROMPT_MODULES[k] for k in selected["tasks"]]
    return (
        EDIT_BASE_PROMPT
        + "\n" + EDIT_COMBINATION_RULES
        + "\n本次处理任务：" + "、".join(names)
        + "\n" + "\n".join(modules)
        + SCREEN_CONTEXT_RULES
    )
