# Clef's joint schema head receives every task definition in the schema once.
def joint_router_input(state):
    return ("共同意图边界：\n" + CLEF_ROUTING_PROMPT + "\n\n联合分类规则：\n" + JOINT_ROUTING_RULES
            + "\n\n待分类输入（仅下列口述代表本次请求）：\n" + state)


def routing_schema(*, target=None):
    available = available_edit_tasks(target)
    return {
        "voice_intent": {
            "type": "choice",
            "instructions": "依据 state 中的共同意图边界及本次 schema 中的可用任务定义，判断当前用户是在提供正文，还是要求系统执行文字处理。",
            "criteria": dict(CLEF_ROUTING_CRITERIA),
        },
        **{
            name: {
                "type": "choice",
                "instructions": "依据共同意图边界和联合分类规则，判断当前用户是否实际要求此任务。" + description,
                "criteria": dict(EDIT_TASK_CRITERIA[name]),
            }
            for name, description in EDIT_TASK_DESCRIPTIONS.items()
            if name in available
        },
    }
