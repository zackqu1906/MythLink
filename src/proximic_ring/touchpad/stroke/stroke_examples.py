def stroke_example(shape):
    example = EXAMPLES.get(shape)
    return f'字例：{example}只写这一笔，不写整个字。' if example else ''


def task_example(task):
    if task.get('kind', 'stroke') != 'stroke':
        return ''
    shape = task.get('shape') or task.get('title', '').split(' · ', 1)[0]
    return stroke_example(shape)
